"""Collect results/papers/*.json into PAPERS_RESULTS.md (tables only)."""
import glob
import json
import os
import re


def load(p):
    return json.load(open(p)) if os.path.exists(p) else None


def rng(lb, ub):
    if lb is not None and ub is not None and lb == ub:
        return f"**{lb}**"
    return f"{lb if lb is not None else '?'} – {ub if ub is not None else '?'}"


HEAD = {}          # mitten: code -> {claimed, Z: (lb, ub), X: (lb, ub)}
AMP = {}           # amplified: (level, basis) -> (lb, ub) under the paper's fault model
BBH = {}           # bb: circuit -> (code distance text, lb, ub, one-round window text)

out = ["# Results: circuit distance of published qLDPC memory circuits", "",
       "Generated by `scripts/summarize_papers.py` from `results/papers/*.json`.",
       "Lower bound = exhaustive exclusion (certified by search); upper bound = fault set verified in the full DEM "
       "and replayed physically in Stim.", ""]

# ------------------------------------------------------------------ mitten
out += ["## Mitten codes (arXiv:2607.28795), published \"hook-free\" SE schedules", "",
        "| code | claimed distance | basis | exhaustive exclusion up to | certified lower bound | verified upper bound | circuit distance | witness circuit |",
        "|---|---:|:-:|---:|---:|---:|---:|---|"]
codes = sorted({re.match(r"mitten(\d+)_", os.path.basename(f)).group(1) for f in glob.glob("results/papers/mitten[0-9]*_[ZX]*.json")}, key=int)
for n in codes:
    for b in "ZX":
        lb = ub = None
        claimed = None
        name = None
        wit = None
        for f in sorted(glob.glob(f"results/papers/mitten{n}_{b}*.json")):
            r = load(f)
            claimed = r.get("claimed_distance", claimed)
            name = r.get("code", name)
            if "runs" in r:
                done = [x["K"] for x in r["runs"] if x["status"] == "exhausted" and x["best"] is None]
                if done:
                    lb = max(lb or 0, max(done) + 1)
                if r.get("distance") is not None:
                    lb = max(lb or 0, r["distance"])
            if r.get("certified_upper_bound") is not None and (ub is None or r["certified_upper_bound"] < ub):
                ub = r["certified_upper_bound"]
                wit = r["witness"]
        if name is None:
            continue
        HEAD.setdefault(name, {"claimed": claimed})[b] = (lb, ub)
        out.append(f"| {name} | {claimed} | {b} | {lb - 1 if lb else '–'} | {lb if lb else '–'} | {ub if ub else '–'} | "
                   f"{rng(lb, ub)} | {wit['rounds']} rounds, {wit['weight']} faults, verified: {wit['verified']} |" if wit else
                   f"| {name} | {claimed} | {b} | {lb - 1 if lb else '–'} | {lb if lb else '–'} | – | {rng(lb, ub)} | – |")
out.append("")
cd = load("results/papers/mitten_code_distance.json")
if cd:
    out += ["Code distance with data errors only (no hooks), by the same search:", "",
            "| code | basis | code distance found | seconds |", "|---|:-:|---:|---:|"]
    for k, v in cd.items():
        name, b = k.split(":")
        out.append(f"| {name} | {b} | {v['code_distance_found']} | {v['seconds']} |")
    out.append("")
wfiles = [load(f) for f in sorted(glob.glob("results/papers/mitten*.json"))]
wfiles = [r["witness"] for r in wfiles if isinstance(r, dict) and isinstance(r.get("witness"), dict)
          and "collapsed_columns_equal_window_columns" in r["witness"]]
if wfiles:
    out += [f"Consistency of the two constructions: in {sum(1 for w in wfiles if w['collapsed_columns_equal_window_columns'])} "
            f"of {len(wfiles)} witness checks the distance problem built from the matrices and schedule has exactly the "
            f"same columns as the single-round window of the Stim circuit; {sum(1 for w in wfiles if w['verified'])} of "
            f"{len(wfiles)} witnesses replay with no detector firing.", ""]
ml = [load(f) for f in sorted(glob.glob("results/papers/mitten*_milp.json"))]
if ml:
    out += ["Independent solver (SciPy / HiGHS mixed-integer program) on the same problem:", "",
            "| code | basis | best solution found | proven lower bound | proved optimal | seconds |", "|---|:-:|---:|---:|:-:|---:|"]
    for r in ml:
        out.append(f"| {r['code']} | {r['basis']} | {r['objective']} | {int(r['dual_bound'] + 0.999) if r.get('dual_bound') is not None else '–'} | "
                   f"{'yes' if r['proved_optimal'] else 'no'} | {r['seconds']} |")
    out.append("")
idle = load("results/papers/mitten_idle_sensitivity.json")
if idle:
    same = all(v["identical_collapsed_problem"] for v in idle.values())
    out += [f"Idle-fault sensitivity: adding a depolarizing fault on every idle data qubit leaves the distance problem "
            f"unchanged for {', '.join(sorted({k.split(':')[0] for k in idle}))} (identical column sets: {same}).", ""]

# ------------------------------------------------------------------ amplified
out += ["## Amplified qLDPC memories (arXiv:2609.37231), authors' circuit builder", "",
        "Certified bound of the paper: 3 x 2^level; target (static distance): 4 x 2^level.", "",
        "| level | code | rounds | basis | fault model | paper: certified ≥ / target | collapsed | certified lower | verified upper | circuit distance | seconds |",
        "|---:|---|---:|:-:|---|---|---:|---:|---:|---:|---:|"]
nk = {0: "[[18,4,4]]", 1: "[[90,8,8]]", 2: "[[468,16,16]]", 3: "[[2484,32,32]]"}
for f in sorted(glob.glob("results/papers/amp[0-9]_r*_[ZX]*.json")):
    r = load(f)
    m = re.match(r"amp(\d)_r(\d+)_([ZX])(_idle)?(.*)\.json", os.path.basename(f))
    if not m or "stages" not in r:
        continue
    lv, rounds, b, idle_, _ = m.groups()
    lv = int(lv)
    paper = f"{3 * 2 ** lv if lv else 4} / {4 * 2 ** lv}"
    if not idle_:
        AMP[(lv, b)] = (r.get("certified_lower_bound"), r.get("certified_upper_bound"))
    out.append(f"| {lv} | {nk[lv]} | {rounds} | {b} | {'paper + idle data faults' if idle_ else 'paper (no idle)'} | {paper} | "
               f"{r['stages']['collapsed']['distance']} | {r.get('certified_lower_bound')} | {r.get('certified_upper_bound')} | "
               f"{rng(r.get('certified_lower_bound'), r.get('certified_upper_bound'))} | {r.get('seconds')} |")
for b in "ZX":
    lb = ub = None
    rounds = None
    for f in sorted(glob.glob(f"results/papers/amp2_*_{b}*.json")):
        r = load(f)
        if "stages" in r:
            continue
        if r.get("certified_upper_bound") is not None:
            ub = min(ub or 10 ** 9, r["certified_upper_bound"])
        if "collapsed" in r and r["collapsed"].get("runs"):
            done = [x["K"] for x in r["collapsed"]["runs"] if x["status"] == "exhausted" and x["best"] is None]
            if done:
                lb = max(lb or 0, max(done) + 1)
        rounds = re.search(r"_r(\d+)_", os.path.basename(f)).group(1)
    if lb or ub:
        AMP[(2, b)] = (lb, ub)
        out.append(f"| 2 | {nk[2]} | {rounds} | {b} | paper (no idle) | 12 / 16 | – | {lb if lb else '–'} (ours) | {ub if ub else '–'} | "
                   f"{rng(max(lb or 0, 12), ub)} using the paper's bound 12 | – |")
out.append("")

# ------------------------------------------------------------------ BB
out += ["## IBM bivariate bicycle codes (arXiv:2308.07915), tesseract-decoder SI1000 circuits", "",
        "The upper bound is the lightest fault set found by information-set search in one bulk round; it can be "
        "above the true value (for BB756 it is above the code-distance claim, i.e. uninformative).", "",
        "Files of the later runs with the covering bound (`results/phase4/`) are included.", "",
        "| circuit | claimed code distance | code distance (data-error window) | collapsed relaxation | one-round window distance | certified lower bound | lightest verified fault set | circuit distance |",
        "|---|---:|---|---|---|---:|---:|---:|"]
for code, claimed in (("bb360_r24", "≤ 24"), ("bb756_r34", "≤ 34")):
    for b in "ZX":
        lb = ub = None
        cap = "–"
        col = "–"
        win1 = "–"
        seen = False
        for f in sorted(glob.glob(f"results/papers/{code}_{b}*.json")) + sorted(glob.glob(f"results/phase4/*{code}_{b}.json")):
            r = load(f)
            seen = True
            if "collapsed" in r and r["collapsed"].get("runs"):
                done = [x["K"] for x in r["collapsed"]["runs"] if x["status"] == "exhausted" and x["best"] is None]
                if done:
                    lb = max(lb or 0, max(done) + 1)
                if done and not col.startswith("distance"):
                    prev = int(col.split()[-1]) if col.startswith("no solution") else 0
                    col = f"no solution ≤ {max(max(done), prev)}"
                if r["collapsed"].get("distance") is not None:
                    lb = max(lb or 0, r.get("certified_lower_bound") or 0)
                    nl = sum(1 for x in r["collapsed"].get("lifts", []) if x["lift_slack0"] is not None)
                    col = (f"distance {r['collapsed']['distance']}; {nl} of {r['collapsed'].get('n_orbits')} "
                           f"solution orbits lift")
            if r.get("certified_upper_bound") is not None:
                ub = min(ub or 10 ** 9, r["certified_upper_bound"])
            if r.get("window") == [0, 0] and "runs" in r:
                done = [x["K"] for x in r["runs"] if x["status"] == "exhausted"]
                wd = r.get("window_distance")
                if wd is not None:
                    cap = f"{wd} (exact)"
                elif done and not cap.endswith("(exact)"):
                    prev = int(cap.split()[-1]) if cap.startswith("≥") else 0
                    cap = f"≥ {max(max(done) + 1, prev)}"
            if r.get("window") == [1, 1] and r.get("window_distance") is not None:
                win1 = f"{r['window_distance']} (exact)"
        if seen:
            BBH[f"{code}_{b}"] = (cap, lb, ub, win1)
            out.append(f"| {code}_{b} | {claimed} | {cap if b == 'Z' else '–'} | {col} | {win1} | {lb if lb else '–'} | {ub if ub else '–'} | {rng(lb, ub)} |")
out.append("")

open("docs/PAPERS_RESULTS.md", "w").write("\n".join(out) + "\n")

# ------------------------------------------------------------------ headline tables inside PAPERS.md
h = ["**Mitten codes** (published \"hook-free\" schedules; paper's fault model). "
     "Bold = exact; otherwise certified lower bound – verified upper bound.", "",
     "| code | claimed distance | circuit distance, Z basis | circuit distance, X basis | below the claim? |",
     "|---|---:|---:|---:|---|"]
for name in sorted(HEAD, key=lambda x: int(x.strip("[]").split(",")[0])):
    v = HEAD[name]
    ubs = [v[b][1] for b in "ZX" if b in v and v[b][1] is not None]
    below = "yes" if ubs and min(ubs) < v["claimed"] else "not shown"
    est = int(name.strip("[]").split(",")[0]) >= 630      # the paper gives these three distances as estimates
    h.append(f"| {name} | {'≤ ' if est else ''}{v['claimed']} | {rng(*v.get('Z', (None, None)))} | {rng(*v.get('X', (None, None)))} | {below} |")
h += ["", "**Amplified qLDPC memories** (authors' circuits, 8 rounds for levels 0 and 1; paper's fault model).", "",
      "| level | code | paper: certified ≥ | paper: target | circuit distance, Z | circuit distance, X |",
      "|---:|---|---:|---:|---:|---:|"]
for lv in sorted({k[0] for k in AMP}):
    cells = []
    for b in "ZX":
        lb, ub = AMP.get((lv, b), (None, None))
        if lv == 2:
            cells.append(f"ours ≥ {lb if lb else '?'}; with the paper's bound: 12 – {ub if ub else '?'}")
        else:
            cells.append(rng(lb, ub))
    h.append(f"| {lv} | {nk[lv]} | {3 * 2 ** lv if lv else 4} | {4 * 2 ** lv} | {cells[0]} | {cells[1]} |")
h += ["", "**IBM bivariate bicycle codes** (tesseract-decoder SI1000 circuits, rounds = claimed distance).", "",
      "| circuit | claimed code distance | code distance (from the Z-basis data-error window) | distance within one round | circuit distance |",
      "|---|---:|---|---|---|"]
for k in sorted(BBH):
    cap, lb, ub, win1 = BBH[k]
    claimed_d = 24 if "360" in k else 34
    cd = rng(lb, ub) if ub is not None and ub <= claimed_d else f"≥ {lb} (no informative upper bound)"
    h.append(f"| {k} | ≤ {claimed_d} | {cap if k.endswith('Z') else '–'} | {win1} | {cd} |")
if os.path.exists("docs/PAPERS.md"):
    t = open("docs/PAPERS.md").read()
    a, bmark = "<!-- RESULTS:BEGIN -->", "<!-- RESULTS:END -->"
    if a in t and bmark in t:
        t = t[:t.index(a) + len(a)] + "\n" + "\n".join(h) + "\n" + t[t.index(bmark):]
        open("docs/PAPERS.md", "w").write(t)
print("\n".join(out))
