"""Collect results/*.json into RESULTS.md (tables only; no numbers typed by hand)."""
import glob
import json
import os

CODES = [("bb72_r6", "[[72,12,6]]", 6), ("bb90_r10", "[[90,8,10]]", 10), ("bb108_r10", "[[108,8,10]]", 10),
         ("bb144_r12", "[[144,12,12]]", 12), ("bb288_r18", "[[288,12,18]]", 18)]


LAB = {"code_capacity": "window t=0", "collapsed_circuit": "collapsed circuit"}


def load(p):
    return json.load(open(p)) if os.path.exists(p) else None


def log_wall(path):
    """Wall time of a run from the first and last timestamp of its log."""
    if not os.path.exists(path):
        return 0
    ts = [ln[:8] for ln in open(path) if len(ln) > 8 and ln[2] == ":" and ln[5] == ":"]
    if len(ts) < 2:
        return 0
    sec = lambda t: int(t[:2]) * 3600 + int(t[3:5]) * 60 + int(t[6:8])
    return (sec(ts[-1]) - sec(ts[0])) % 86400


def fmt_nodes(n):
    return f"{n:.2e}" if n >= 1e6 else str(n)


out = ["# Results", "", "Generated by `scripts/summarize.py` from `results/*.json`.", ""]

# ---------------------------------------------------------------- main table
out += ["## Circuit distance of the pinned BB memory circuits", "",
        "All circuits: tesseract-decoder test data (SI1000, p = 0.001, CZ-compiled), rounds = code distance.",
        "Lower bound = exhaustive exclusion; upper bound = witness verified in the full DEM and replayed physically.",
        "",
        "| code | rounds | basis | code distance | collapsed | fold-2 | fold-3 | certified lower | verified upper | circuit distance | method | wall time |",
        "|---|---:|:-:|---:|---:|---:|---:|---:|---:|---:|---|---:|"]
for code, label, dcode in CODES:
    rounds = int(code.split("_r")[1])
    for b in "ZX":
        name = f"{code}_{b}"
        r = load(f"results/{name}.json")
        if r is None:
            continue
        if "stages" in r:   # scripts/run_bb.py
            st = r["stages"]
            lb, ub = r.get("certified_lower_bound"), r.get("certified_upper_bound")
            out.append(f"| {label} | {rounds} | {b} | {dcode} | {st['collapsed']['distance']} | {st['fold2']['distance']} | "
                       f"{st['fold3']['distance']} | {lb} | {ub} | **{lb if lb == ub else f'{lb}–{ub}'}** | direct search | "
                       f"{r['seconds']} s ({r['threads']} thr) |")
        else:               # scripts/run_deep.py (+ top-down)
            td = load(f"results/topdown_{name}_W15.json")
            lb = r.get("certified_lower_bound")
            ub = r.get("certified_upper_bound")
            secs = r.get("seconds", 0)
            if td and td.get("certified_lower_bound"):
                lb = max(lb, td["certified_lower_bound"])
                secs += td["seconds"]
            secs += log_wall(f"results/enum_{name}.log")
            out.append(f"| {label} | {rounds} | {b} | {dcode} | {r.get('collapsed', {}).get('distance')} | – | – | {lb} | {ub} | "
                       f"**{lb if lb == ub else f'{lb}–{ub}'}** | windows, collapsed search, enumeration, top-down lift | {secs:.0f} s ({r['threads']} thr) |")
out.append("")

# ---------------------------------------------------------------- BB288 detail
for b in "ZX":
    name = f"bb288_r18_{b}"
    r = load(f"results/{name}.json")
    if r is None:
        continue
    out += [f"## BB288, {b} basis: evidence chain", ""]
    m = r["model"]
    out.append(f"- model: {m['detectors']} detectors, {m['dem_mechanisms']} DEM mechanisms -> sector "
               f"{m['sector_rows']} x {m['sector_columns']} (exact: {m['sector_reduction_exact']}) -> collapsed "
               f"{m['collapsed_rows']} x {m['collapsed_columns']}")
    for tw in (0, 1):
        w = r.get(f"window_t{tw}")
        if w:
            wit = w.get("witness", {})
            out.append(f"- window t={tw}: {w['columns']} columns, exact window distance {w['distance']}; "
                       f"witness verified: {wit.get('verified')} (replay: detectors {wit.get('replay', {}).get('fired_detectors')}, "
                       f"observables {wit.get('replay', {}).get('flipped_observables')})")
    c = r.get("collapsed", {"runs": []})
    out.append(f"- collapsed relaxation: distance {c.get('distance')} "
               f"({c.get('n_min_solutions')} minimum solutions in {c.get('n_orbits')} translation orbits); "
               f"orbits lifting exactly: {sum(1 for x in c.get('lifts', []) if x['lift_slack0'] is not None)}")
    out += ["", "| K | status | nodes | seconds |", "|---:|---|---:|---:|"]
    for x in c["runs"]:
        if x["K"] >= 9:
            out.append(f"| {x['K']} | {x['status']}{'' if x['best'] is None else ' (solutions found)'} | {fmt_nodes(x['nodes'])} | {x['seconds']} |")
    out.append("")
    en = load(f"results/enum_{name}.json")
    td = load(f"results/topdown_{name}_W15.json")
    if en and td:
        out += ["Top-down exclusion of weight <= 15 in the real circuit:", "",
                "| collapsed weight | solutions | orbits | extra faults allowed | orbits that lift | search nodes |",
                "|---:|---:|---:|---:|---:|---:|"]
        for w in sorted(td["by_weight"], key=int):
            v = td["by_weight"][w]
            ew = en["weights"].get(w, en["weights"].get(str(w), {}))
            out.append(f"| {w} | {ew.get('solutions')} | {v['orbits']} | {v['slack']} | {v['lifting_orbits']} | {fmt_nodes(v['nodes'])} |")
        out += ["", f"Result: certified lower bound {td.get('certified_lower_bound')}" if td["found"] is None
                else f"Result: real solution of weight {td['found']['weight']} found", ""]

# ---------------------------------------------------------------- widths
d = load("results/dense.json")
if d:
    out += ["## Widths: Rank DP vs tensor network (heuristic upper bounds)", "",
            "Cut rank = largest interface dimension of the linear Rank DP (greedy order). "
            "TN treewidth = min-fill bound for the Tanner graph (direct picture) and for the detector graph (Fourier picture). "
            "A dense table needs 2^width entries.", "",
            "| instance | problem | columns | rank | Rank DP cut rank | TN sweep, original checks | TN Tanner treewidth | TN detector treewidth |",
            "|---|---|---:|---:|---:|---:|---:|---:|"]
    for code in d:
        for lab in ("code_capacity", "collapsed_circuit"):
            v = d[code].get(lab)
            if not v:
                continue
            out.append(f"| {code} | {LAB[lab]} | {v['columns']} | {v['rank']} | {v['rankdp_cut_rank']} | "
                       f"{v['tn_sweep_width_original_checks']} | {v['tn_tanner_treewidth_minfill']} | {v['tn_detector_graph_treewidth_minfill']} |")
    wr = load("results/widths_real.json")
    if wr:
        out += ["", "Real multi-round circuits (sector problem, time-ordered sweep) for comparison:", "",
                "| instance | rows x columns | cut rank, real circuit | cut rank, collapsed |", "|---|---|---:|---:|"]
        for k, v in wr.items():
            out.append(f"| {k} | {v['sector_rows']} x {v['sector_columns']} | {v['cut_rank_time_ordered']} | {v['collapsed_cut_rank']} |")
    out += ["", "## Dense runs on a laptop (tables up to 2^28 bytes, tensors up to rank 28)", "",
            "| instance | problem | dense Rank DP distance | table bits | seconds (all observables) | tropical TN (observable 0) | TN largest tensor rank needed | TN seconds |",
            "|---|---|---:|---:|---:|---:|---:|---:|"]
    for code in d:
        for lab in ("code_capacity", "collapsed_circuit"):
            v = d[code].get(lab)
            if not v:
                continue
            dr = v.get("dense_rankdp")
            tt = v.get("tropical_tn", {})
            if not dr and not tt:
                continue
            ran_tn = isinstance(tt.get("observable_0"), int)
            out.append(f"| {code} | {LAB[lab]} | {dr['distance'] if dr else 'too large here'} | "
                       f"{dr['peak_table_bits'] if dr else '–'} | {dr['seconds'] if dr else '–'} | "
                       f"{tt.get('observable_0') if ran_tn else 'too large here'} | "
                       f"{tt.get('largest_tensor_rank')} | {tt.get('seconds') if ran_tn else '–'} |")
    out += ["", "## Sum-product at small fault weight x (same sweep, ordinary arithmetic)", "",
            "Z(x) = sum over undetected logical fault sets of x^weight; the exponent is the distance and the prefactor "
            "the number of minimum-weight fault sets flipping that observable.", "",
            "| instance | problem | observable | fitted exponent | multiplicity from Z(x) | multiplicity by enumeration |",
            "|---|---|---:|---:|---:|---:|"]
    for code in d:
        for lab in ("code_capacity", "collapsed_circuit"):
            sp = d[code].get(lab, {}).get("sum_product_small_x")
            if not sp:
                continue
            for i, x in enumerate(sp["per_observable"][:4]):
                out.append(f"| {code} | {LAB[lab]} | {i} | {x['exponent']} | {x['multiplicity']} | {x['multiplicity_by_enumeration']} |")
    out += ["", "## Width-truncated Rank DP (rows dropped until the cut rank fits)", "",
            "| instance | problem | true distance | allowed cut rank | rows dropped | certified lower bound |",
            "|---|---|---:|---:|---:|---:|"]
    for code in d:
        for lab in ("code_capacity", "collapsed_circuit"):
            v = d[code].get(lab, {})
            for x in v.get("truncated_rankdp", []):
                out.append(f"| {code} | {LAB[lab]} | {v['search_distance']} | {x['max_cut_rank']} | "
                           f"{x['rows_dropped']} of {x['rows_total']} | {x['lower_bound']} |")
    out.append("")

big = sorted(glob.glob("results/dense_big_*_obs*.json"))
if big:
    groups = {}
    for f in big:
        r = load(f)
        groups.setdefault((r["circuit"], r["problem"]), []).append(r)
    out += ["## Dense Rank DP near the memory limit", "",
            "| circuit | problem | columns | cut rank | largest table | observables run | distance (min over them) | seconds per observable | threads per observable |",
            "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    for (circ, prob), rs in groups.items():
        po = [x for r in rs for x in r["per_observable"] if isinstance(x.get("distance"), int)]
        if not po:
            continue
        out.append(f"| {os.path.basename(circ)} | {prob} | {rs[0]['columns']} | {rs[0]['cut_rank']} | "
                   f"2^{max(x['peak_bits'] for x in po)} bytes | {len(po)} | {min(x['distance'] for x in po)} | "
                   f"{min(x['seconds'] for x in po):.0f}–{max(x['seconds'] for x in po):.0f} | {rs[0]['threads']} |")
    out.append("")

deep = sorted(glob.glob("results/deep_bb*.json")) + sorted(glob.glob("results/bb288_r18_?.json"))
if deep:
    out += ["## Single-layer windows (upper bounds) and the collapsed relaxation (lower bound)", "",
            "Window t=0: faults detected only in the first detector layer (for the Z-basis circuits these are exactly "
            "the data errors, so its distance is the code distance). Window t=1: one bulk layer.", "",
            "| circuit | window t=0: columns, distance | window t=1: columns, distance | collapsed distance | minimum collapsed solutions (orbits) | orbits lifting exactly |",
            "|---|---|---|---:|---:|---:|"]
    for f in deep:
        r = load(f)
        w0, w1, c = r.get("window_t0", {}), r.get("window_t1", {}), r.get("collapsed", {})
        nl = sum(1 for x in c.get("lifts", []) if x["lift_slack0"] is not None)
        out.append(f"| {os.path.basename(r['circuit'])} | {w0.get('columns')}, {w0.get('distance')} | {w1.get('columns')}, {w1.get('distance')} | "
                   f"{c.get('distance')} | {c.get('n_min_solutions')} ({c.get('n_orbits')}) | {nl} |")
    out.append("")

cc = sorted(glob.glob("results/crosscheck_bb*.json"))
if cc:
    out += ["## Consistency: anchored search (symmetry + exclusions) vs plain search", "",
            "| circuit (collapsed problem) | thresholds | anchored: distance / lower bound / solutions | plain: distance / lower bound / solutions | agree |",
            "|---|---:|---|---|:-:|"]
    for f in cc:
        r = load(f)
        a, b = r["anchored"], r["plain"]
        out.append(f"| {os.path.basename(r['circuit'])} | 1..{r['K']} | {a['distance']} / {a['lower_bound']} / {a['solutions']} | "
                   f"{b['distance']} / {b['lower_bound']} / {b['solutions']} | {'yes' if r['agree'] else 'NO'} |")
    out.append("")

v = load("results/validate_topdown_small.json")
if v:
    out += ["## Cross-validation: direct search vs top-down route", "",
            "| circuit | direct distance | top-down at W = d-1 | top-down at W = d | agree |", "|---|---:|---|---|:-:|"]
    for r in v:
        d0 = r["direct_distance"]
        a, b = r[f"W={d0 - 1}"], r[f"W={d0}"]
        out.append(f"| {r['circuit']} | {d0} | none; lower bound {a['certified_lower_bound']} | weight {b['found']} found, verified | {'yes' if r['agree'] else 'NO'} |")
    out.append("")

ml = sorted(glob.glob("results/milp*.json"))
if ml:
    ours = {}
    for code, _, _ in CODES:
        for b in "ZX":
            r = load(f"results/{code}_{b}.json")
            if r and "stages" in r:
                ours[f"{code}_{b}"] = {"collapsed": r["stages"]["collapsed"]["distance"], "fold2": r["stages"]["fold2"]["distance"],
                                       "fold3": r["stages"]["fold3"]["distance"], "sector": r["stages"]["full"]["distance"]}
    out += ["## Independent solver cross-check (mixed-integer program, SciPy / HiGHS)", "",
            "Same problem import, nothing else shared. \"Proved\" means HiGHS closed the gap within its time limit; "
            "otherwise its best solution and best proven bound are shown.", "",
            "| instance | problem | rows x columns | this work | HiGHS best solution | HiGHS proven lower bound | proved optimal | seconds |",
            "|---|---|---|---:|---:|---:|:-:|---:|"]
    for f in ml:
        for key, r in load(f).items():
            name, which = key.split(":")
            lbv = r.get("dual_bound")
            lbs = "–" if lbv is None else str(int(-(-lbv // 1)) if abs(lbv - round(lbv)) > 1e-6 else int(round(lbv)))
            out.append(f"| {name} | {which} | {r['rows']} x {r['columns']} | {ours.get(name, {}).get(which)} | {r['objective']} | "
                       f"{lbs} | {'yes' if r['proved_optimal'] else 'no'} | {r['seconds']} |")
    out.append("")

mu = load("results/maxsat_unfinished.json")
if mu:
    out += ["## MaxSAT attempt (Stim's formulation, PySAT RC2)", "",
            "| circuit | variables | hard clauses | outcome |", "|---|---:|---:|---|"]
    for r in mu:
        out.append(f"| {r['circuit']} | {r['vars']} | {r['hard']} | {r['outcome']} |")
    out.append("")

ms = sorted(glob.glob("results/maxsat_bb*.json"))
if ms:
    out += ["## Independent MaxSAT cross-check (Stim formulation, PySAT RC2)", "",
            "| circuit | MaxSAT optimum | seconds |", "|---|---:|---:|"]
    for f in ms:
        r = load(f)
        out.append(f"| {os.path.basename(r['circuit'])} | {r['maxsat_distance']} | {r['seconds']:.0f} |")
    out.append("")

open("docs/notes/RESULTS.md", "w").write("\n".join(out) + "\n")
print("\n".join(out[:40]))
