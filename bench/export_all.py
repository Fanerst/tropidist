def _completed(name):
    directory = Path(common.INSTANCES) / name
    path = directory / "meta.json"
    if not path.is_file():
        return False
    try:
        meta = json.loads(path.read_text())
        return meta["name"] == name and all((directory / (v + ext)).is_file()
                   for v in meta["variants"] for ext in (".H.mtx", ".L.mtx"))
    except (ValueError, KeyError):
        return False


def _statuses():
    out = {}
    for path in OUTPUT.glob("*__export.json"):
        record = json.loads(path.read_text())
        out[record["name"]] = record
    return out


def _source(source):
    if not source:
        return "—"
    path, _, field = source.partition("#")
    if (ROOT / path).is_file():
        link = "[%s](../%s)" % (path, path)
        return link + (" (`%s`)" % field if field else "")
    return source


def write_document(statuses):
    lines = ["# Benchmark instances", "", "Generated by `bench/export_all.py`. Ground truth is read from the cited result files or computed by the named graph algorithm; `unknown` paper claims are not certificates.", "",
             "`--max-cols` bounds raw undecomposed DEM mechanisms for circuits and physical columns for codes. CSS circuit variants `full` and `sector` have identical truth after the exporter checks the sector reduction. `collapsed` is a relaxation with its own truth. The `stim_color` circuit family has only `full`.", "",
             "| name | track | family | n | k | rows × cols per variant | symmetries per variant | ground truth per variant (kind; source) |",
             "|---|---|---|---:|---:|---|---|---|"]
    pending = []
    for name, spec in instances.INSTANCES.items():
        if not _completed(name):
            state = statuses.get(name, {})
            pending.append((name, state.get("status", spec["status"]), state.get("reason", spec.get("reason", "not exported"))))
            continue
        meta = json.loads((Path(common.INSTANCES) / name / "meta.json").read_text())
        shapes, perms, truths = [], [], []
        for v, info in meta["variants"].items():
            shapes.append("%s: %s × %s" % (v, info["rows"], info["cols"]))
            perms.append("%s: %s" % (v, info.get("symmetries", 0)))
            truths.append("%s: %s (%s; %s)" % (v, info.get("distance") if info.get("distance") is not None else "—",
                           info.get("distance_kind", "unknown"), _source(info.get("distance_source"))))
        lines.append("| %s | %s | %s | %s | %s | %s | %s | %s |" %
                     (name, meta["track"], meta["family"], meta.get("n", "—"), meta.get("k", "—"),
                      "<br>".join(shapes), "<br>".join(perms), "<br>".join(truths)))
    if pending:
        lines += ["", "## Pending instances", "", "| name | status | reason |", "|---|---|---|"]
        for name, state, reason in pending:
            lines.append("| %s | %s | %s |" % (name, state, str(reason).replace("|", "\\|")))
        large = [name for name, state, _ in pending if state == "too_large"]
        if large:
            lines += ["", "Server export (no local cap):", "", "```sh", "python bench/export_all.py --only " + ",".join(large), "```"]
    lines += ["", "Mitten-300 records only the lower bound certified by the named result files. The Cornucopia-1044 code-capacity paper claim starts as `unknown`; a local exact result is used only when its certificate is present and its input hashes match the rebuilt matrices.", ""]
    lines += [STIM_NOTES, ""]
    (ROOT / "bench/INSTANCES.md").write_text("\n".join(lines))


def _worker(name, max_cols):
    status = {"name": name}
    start = time.monotonic()
    try:
        meta = instances.build(name, max_cols=max_cols)
        status.update(status="exported", variants=meta["variants"], raw_mechanisms=meta.get("raw_mechanisms"))
    except instances.TooLarge as exc:
        status.update(status="too_large", reason=str(exc))
    except instances.NeedsLead as exc:
        status.update(status="needs_lead", reason=str(exc))
    except Exception as exc:
        status.update(status="needs_lead", reason="%s: %s" % (type(exc).__name__, exc))
    status["seconds"] = round(time.monotonic() - start, 3)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / (name + "__export.json")).write_text(json.dumps(status, indent=1) + "\n")
    print(json.dumps(status), flush=True)
    return 0 if status["status"] in ("exported", "too_large") else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--only", help="comma-separated registry names")
    ap.add_argument("--max-cols", type=int, help="maximum raw DEM mechanisms (code: columns)")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--worker", help=argparse.SUPPRESS)
    a = ap.parse_args()
    if a.max_cols is not None and a.max_cols < 1:
        ap.error("--max-cols must be positive")
    if a.worker:
        return _worker(a.worker, a.max_cols)
    names = [n.strip() for n in a.only.split(",") if n.strip()] if a.only else list(instances.INSTANCES)
    missing = [n for n in names if n not in instances.INSTANCES]
    if missing:
        ap.error("unknown instance(s): " + ",".join(missing))
    names = list(dict.fromkeys(names))
    statuses = _statuses()
    if a.list:
        print("name\ttrack\tfamily\tn\tk\tstatus\ttruth / reason")
        for name in names:
            s = instances.INSTANCES[name]
            saved = statuses.get(name, {})
            status = "exported" if _completed(name) else s["status"] if s["status"] == "needs_lead" else saved.get("status", s["status"])
            truth = "; ".join("%s=%s (%s; %s)" % (v, t[0], t[1], t[2]) for v, t in s.get("truth", {}).items())
            reason = s.get("reason", saved.get("reason", truth)) if status != "exported" else truth
            print("\t".join(str(v) for v in (name, s["track"], s["family"], s.get("n", "?"), s.get("k", "?"), status, reason)))
        return 0
    OUTPUT.mkdir(parents=True, exist_ok=True)
    LOGS.mkdir(parents=True, exist_ok=True)
    failed = False
    for name in names:
        if _completed(name) and not a.force:
            print(name + ": already exported", flush=True)
            continue
        spec = instances.INSTANCES[name]
        if spec["status"] == "needs_lead":
            record = dict(name=name, status="needs_lead", reason=spec["reason"])
        else:
            command = [sys.executable, "-B", str(Path(__file__).resolve()), "--worker", name]
            if a.max_cols is not None:
                command += ["--max-cols", str(a.max_cols)]
            path = OUTPUT / (name + "__export.json")
            if path.exists():
                path.unlink()  # do not mistake a previous run for this worker's outcome
            try:
                with (LOGS / (name + "__export.log")).open("w") as log:
                    child = subprocess.run(command, stdout=log, stderr=subprocess.STDOUT, timeout=295 if sys.platform == "darwin" else None,
                                           env=dict(os.environ, OMP_NUM_THREADS="2", PYTHONDONTWRITEBYTECODE="1"), cwd=str(ROOT))
                record = json.loads(path.read_text()) if path.exists() else dict(name=name, status="needs_lead", reason="worker exited %d without a result" % child.returncode)
            except subprocess.TimeoutExpired:
                record = dict(name=name, status="needs_lead", reason="export exceeded the 295-second local process limit; see logs/bench_dev/suite")
        statuses[name] = record
        (OUTPUT / (name + "__export.json")).write_text(json.dumps(record, indent=1) + "\n")
        if record["status"] == "needs_lead":
            instances.INSTANCES[name].update(status="needs_lead", reason=record["reason"])
            failed = True
        print(name + ": " + record["status"] + (" — " + record["reason"] if "reason" in record else ""), flush=True)
        write_document(statuses)
    write_document(statuses)
    (OUTPUT / "exports.json").write_text(json.dumps(list(statuses.values()), indent=1) + "\n")
    large = [n for n in names if statuses.get(n, {}).get("status") == "too_large"]
    if large:
        print("Server: python bench/export_all.py --only " + ",".join(large), flush=True)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
